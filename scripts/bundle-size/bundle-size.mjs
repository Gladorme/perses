// Measures the size of the UI bundles and compares two measurements (e.g. main branch vs pull request).
// It only relies on Node.js built-in modules so it can run without installing any dependency.
//
// Usage:
//   node bundle-size.mjs measure --output <sizes.json> [--extensions .js,.css] <[name=]directory>...
//     A directory can contain `*` segments matching any sub-directory, e.g. `*/dist/__mf`. Unless a name is given,
//     the bundle is named after the segments matched by `*` (or the directory itself when there are none).
//
//   node bundle-size.mjs compare --base <base.json> --head <head.json> [--base-label <label>] [--head-label <label>]
//     [--output <report.md>]

import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { constants, gzipSync } from 'node:zlib';

const DEFAULT_EXTENSIONS = ['.js', '.mjs', '.cjs', '.css'];
const IGNORED_DIRECTORIES = new Set(['node_modules', '.git', '.turbo']);
// Content hashes generated by rspack/rsbuild, e.g. `main.94196c2ee1eb2a8b.js` or `async/123.1a2b3c4d.js`.
const HASH_REGEX = /\.[0-9a-f]{8,}(?=\.[^./]+$)/;
const MAX_FILE_ROWS = 50;

function parseArgs(argv) {
  const options = {};
  const positionals = [];
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg.startsWith('--')) {
      const value = argv[i + 1];
      if (value === undefined || value.startsWith('--')) {
        throw new Error(`missing value for option ${arg}`);
      }
      options[arg.slice(2)] = value;
      i++;
    } else {
      positionals.push(arg);
    }
  }
  return { options, positionals };
}

function listDirectories(dir) {
  if (!existsSync(dir)) {
    return [];
  }
  return readdirSync(dir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && !entry.name.startsWith('.') && !IGNORED_DIRECTORIES.has(entry.name))
    .map((entry) => entry.name)
    .toSorted();
}

/**
 * Expands a directory pattern where `*` segments match any sub-directory.
 * Returns the existing directories along with the values matched by the wildcards.
 */
function expandPattern(pattern) {
  let candidates = [{ path: '.', matches: [] }];
  for (const segment of pattern.split('/').filter((s) => s !== '' && s !== '.')) {
    const next = [];
    for (const candidate of candidates) {
      if (segment === '*') {
        for (const name of listDirectories(candidate.path)) {
          next.push({ path: join(candidate.path, name), matches: [...candidate.matches, name] });
        }
      } else {
        const path = join(candidate.path, segment);
        if (existsSync(path) && statSync(path).isDirectory()) {
          next.push({ path, matches: candidate.matches });
        }
      }
    }
    candidates = next;
  }
  return candidates;
}

function listFiles(dir, extensions) {
  const files = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) {
      if (!IGNORED_DIRECTORIES.has(entry.name)) {
        files.push(...listFiles(path, extensions));
      }
    } else if (entry.isFile() && extensions.some((ext) => entry.name.endsWith(ext))) {
      files.push(path);
    }
  }
  return files;
}

function measure(options, positionals) {
  if (!options.output) {
    throw new Error('--output is required');
  }
  if (positionals.length === 0) {
    throw new Error('at least one bundle directory is required');
  }
  const extensions = options.extensions ? options.extensions.split(',').map((ext) => ext.trim()) : DEFAULT_EXTENSIONS;

  const bundles = {};
  for (const positional of positionals) {
    const separatorIndex = positional.indexOf('=');
    const name = separatorIndex > 0 ? positional.slice(0, separatorIndex) : undefined;
    const pattern = separatorIndex > 0 ? positional.slice(separatorIndex + 1) : positional;

    for (const { path, matches } of expandPattern(pattern)) {
      const bundleName = name ?? (matches.length > 0 ? matches.join('/') : pattern);
      const files = {};
      for (const file of listFiles(path, extensions)) {
        // Strip content hashes so the same file can be matched between two builds.
        const key = relative(path, file).split(sep).join('/').replace(HASH_REGEX, '');
        const content = readFileSync(file);
        const size = files[key] ?? { raw: 0, gzip: 0 };
        size.raw += content.length;
        size.gzip += gzipSync(content, { level: constants.Z_BEST_COMPRESSION }).length;
        files[key] = size;
      }
      if (Object.keys(files).length > 0) {
        bundles[bundleName] = { files };
      }
    }
  }

  if (Object.keys(bundles).length === 0) {
    throw new Error(`no file found in ${positionals.join(', ')}. Did the build run?`);
  }
  writeFileSync(options.output, JSON.stringify({ bundles }, null, 2));
  console.log(`Measured ${Object.keys(bundles).length} bundle(s), written to ${options.output}`);
}

function total(bundle) {
  const sum = { raw: 0, gzip: 0 };
  for (const size of Object.values(bundle?.files ?? {})) {
    sum.raw += size.raw;
    sum.gzip += size.gzip;
  }
  return sum;
}

function formatBytes(bytes) {
  const abs = Math.abs(bytes);
  if (abs < 1000) {
    return `${bytes} B`;
  }
  if (abs < 1000 * 1000) {
    return `${(bytes / 1000).toFixed(2)} kB`;
  }
  return `${(bytes / 1000 / 1000).toFixed(2)} MB`;
}

function formatDiff(base, head) {
  const diff = head - base;
  if (diff === 0) {
    return '0 B';
  }
  const sign = diff > 0 ? '+' : '-';
  const percent = base === 0 ? '' : ` (${sign}${((Math.abs(diff) / base) * 100).toFixed(2)}%)`;
  const icon = diff > 0 ? '🔺' : '🔽';
  return `${icon} ${sign}${formatBytes(Math.abs(diff))}${percent}`;
}

function formatSize(size, exists) {
  return exists ? formatBytes(size) : '-';
}

function escapeMarkdown(text) {
  return text.replace(/[|`*_<>[\]\\]/g, (char) => `\\${char}`);
}

function bundleTable(rows) {
  return [
    '| Bundle | Base (gzip) | PR (gzip) | Diff (gzip) | Base (raw) | PR (raw) | Diff (raw) |',
    '| :--- | ---: | ---: | ---: | ---: | ---: | ---: |',
    ...rows.map(
      (row) =>
        `| ${escapeMarkdown(row.name)}${row.inBase ? '' : ' (new)'}${row.inHead ? '' : ' (removed)'} ` +
        `| ${formatSize(row.base.gzip, row.inBase)} | ${formatSize(row.head.gzip, row.inHead)} ` +
        `| ${formatDiff(row.base.gzip, row.head.gzip)} ` +
        `| ${formatSize(row.base.raw, row.inBase)} | ${formatSize(row.head.raw, row.inHead)} ` +
        `| ${formatDiff(row.base.raw, row.head.raw)} |`,
    ),
  ];
}

function compare(options) {
  if (!options.base || !options.head) {
    throw new Error('--base and --head are required');
  }
  const base = JSON.parse(readFileSync(options.base, 'utf8')).bundles;
  const head = JSON.parse(readFileSync(options.head, 'utf8')).bundles;
  const baseLabel = options['base-label'] ?? 'base';
  const headLabel = options['head-label'] ?? 'head';

  const names = [...new Set([...Object.keys(base), ...Object.keys(head)])].toSorted();
  const changedBundles = [];
  const unchangedBundles = [];
  const changedFiles = [];
  const baseTotal = { raw: 0, gzip: 0 };
  const headTotal = { raw: 0, gzip: 0 };

  for (const name of names) {
    const row = { name, base: total(base[name]), head: total(head[name]), inBase: name in base, inHead: name in head };
    baseTotal.raw += row.base.raw;
    baseTotal.gzip += row.base.gzip;
    headTotal.raw += row.head.raw;
    headTotal.gzip += row.head.gzip;

    const baseFiles = base[name]?.files ?? {};
    const headFiles = head[name]?.files ?? {};
    let changed = !row.inBase || !row.inHead;
    for (const file of new Set([...Object.keys(baseFiles), ...Object.keys(headFiles)])) {
      const baseFile = baseFiles[file];
      const headFile = headFiles[file];
      if (baseFile?.raw !== headFile?.raw || baseFile?.gzip !== headFile?.gzip) {
        changed = true;
        changedFiles.push({
          bundle: name,
          file,
          base: baseFile ?? { raw: 0, gzip: 0 },
          head: headFile ?? { raw: 0, gzip: 0 },
          inBase: baseFile !== undefined,
          inHead: headFile !== undefined,
        });
      }
    }
    (changed ? changedBundles : unchangedBundles).push(row);
  }

  const lines = ['## 📦 Bundle size report', '', `Comparing ${headLabel} against ${baseLabel}.`, ''];
  lines.push(
    `- **Total gzip size:** ${formatBytes(baseTotal.gzip)} → ${formatBytes(headTotal.gzip)} ` +
      `· ${formatDiff(baseTotal.gzip, headTotal.gzip)}`,
    `- **Total raw size:** ${formatBytes(baseTotal.raw)} → ${formatBytes(headTotal.raw)} ` +
      `· ${formatDiff(baseTotal.raw, headTotal.raw)}`,
    '',
  );

  if (changedBundles.length === 0) {
    lines.push('No bundle size change detected. ✅', '');
  } else {
    lines.push(...bundleTable(changedBundles), '');
  }

  if (changedFiles.length > 0) {
    changedFiles.sort(
      (a, b) =>
        Math.abs(b.head.gzip - b.base.gzip) - Math.abs(a.head.gzip - a.base.gzip) ||
        a.bundle.localeCompare(b.bundle) ||
        a.file.localeCompare(b.file),
    );
    lines.push(`<details><summary>Changed files (${changedFiles.length})</summary>`, '');
    lines.push('| Bundle | File | Base (gzip) | PR (gzip) | Diff (gzip) |', '| :--- | :--- | ---: | ---: | ---: |');
    for (const file of changedFiles.slice(0, MAX_FILE_ROWS)) {
      lines.push(
        `| ${escapeMarkdown(file.bundle)} | ${escapeMarkdown(file.file)} ` +
          `| ${formatSize(file.base.gzip, file.inBase)} | ${formatSize(file.head.gzip, file.inHead)} ` +
          `| ${formatDiff(file.base.gzip, file.head.gzip)} |`,
      );
    }
    if (changedFiles.length > MAX_FILE_ROWS) {
      lines.push('', `_…and ${changedFiles.length - MAX_FILE_ROWS} more file(s) with a smaller change._`);
    }
    lines.push('', '</details>', '');
  }

  if (unchangedBundles.length > 0) {
    lines.push(`<details><summary>Unchanged bundles (${unchangedBundles.length})</summary>`, '');
    lines.push(...bundleTable(unchangedBundles), '', '</details>', '');
  }

  lines.push('<sub>File names are compared with their content hash removed. Source maps are excluded.</sub>');

  const report = lines.join('\n') + '\n';
  if (options.output) {
    writeFileSync(options.output, report);
  }
  console.log(report);
}

function main() {
  const [command, ...rest] = process.argv.slice(2);
  const { options, positionals } = parseArgs(rest);
  switch (command) {
    case 'measure':
      measure(options, positionals);
      break;
    case 'compare':
      compare(options);
      break;
    default:
      throw new Error(`unknown command "${command ?? ''}", expected "measure" or "compare"`);
  }
}

try {
  main();
} catch (error) {
  console.error(`bundle-size: ${error.message}`);
  process.exit(1);
}
