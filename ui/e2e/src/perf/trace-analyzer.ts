/**
 * Extracts React Performance Tracks (https://react.dev/reference/dev-tools/react-performance-tracks) and main thread
 * metrics from a Chrome trace: a trace recorded by the perf harness, or a trace saved from the Chrome DevTools
 * Performance panel.
 *
 * This file has no relative import so it can run directly with Node.js:
 *   node ui/e2e/src/perf/trace-analyzer.ts <trace.json|trace.json.gz> [--top=30] [--json]
 */

import { readFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { gunzipSync } from 'node:zlib';

export const ACTION_MARK = 'perf:action';
export const IDLE_MARK = 'perf:idle';

const COMPONENTS_TRACK = 'Components \u269b';
const SCHEDULER_TRACK_GROUP = 'Scheduler \u269b';
const CHANGED_PROPS_PREFIX = '\u200b';
const DEEPLY_EQUAL_HINT = 'deeply equal';
const LONG_TASK_MS = 50;

interface TraceEvent {
  name: string;
  cat?: string;
  ph: string;
  ts: number;
  dur?: number;
  pid: number;
  tid: number;
  id2?: { local?: string; global?: string };
  id?: string;
  args?: Record<string, unknown> & { data?: Record<string, unknown>; detail?: string };
}

interface DevToolsDetail {
  track?: string;
  trackGroup?: string;
  color?: string;
  properties?: Array<[string, string]> | null;
}

interface TrackEntry {
  name: string;
  start: number;
  end: number;
  track: string;
  trackGroup?: string;
  color?: string;
  properties?: Array<[string, string]> | null;
}

export interface ComponentStats {
  name: string;
  renders: number;
  renderMs: number;
  maxRenderMs: number;
  effects: number;
  effectMs: number;
  /** Development builds only: renders whose props changed, and which top-level props changed. */
  changedPropsRenders: number;
  changedProps: Record<string, number>;
  /** Development builds only: props that changed by reference while being deeply equal. */
  deeplyEqualProps: Record<string, number>;
}

export interface SchedulerTrackStats {
  renders: number;
  renderMs: number;
  commits: number;
  commitMs: number;
  effectsMs: number;
}

export interface TraceSummary {
  /** Duration between the start of the action (or navigation) and the end of the window. */
  windowMs: number;
  /** Time between the start of the action and the end of the last React commit. */
  lastCommitMs: number;
  react: {
    renderPasses: number;
    renderMs: number;
    commits: number;
    commitMs: number;
    effectsMs: number;
    componentRenders: number;
    mounts: number;
    unmounts: number;
    cascadingUpdates: number;
    byTrack: Record<string, SchedulerTrackStats>;
    /** Development builds only: component and method that scheduled updates, e.g. "Panel setState()". */
    updateSources: Record<string, number>;
    cascadingUpdateSources: Record<string, number>;
  };
  mainThread: {
    taskMs: number;
    longTasks: number;
    longestTaskMs: number;
    totalBlockingTimeMs: number;
    scriptingMs: number;
    styleMs: number;
    layoutMs: number;
    paints: number;
  };
  network: {
    queryRequests: number;
  };
  components: ComponentStats[];
}

function round(value: number): number {
  return Math.round(value * 10) / 10;
}

function parseDetail(event: TraceEvent): DevToolsDetail | undefined {
  const detail = event.args?.detail;
  if (typeof detail !== 'string') return undefined;
  try {
    const parsed = JSON.parse(detail) as { devtools?: DevToolsDetail };
    return parsed.devtools;
  } catch {
    return undefined;
  }
}

function increment(record: Record<string, number>, key: string): void {
  record[key] = (record[key] ?? 0) + 1;
}

function isRenderColor(color: string | undefined): boolean {
  // React colors renders with primary/tertiary shades and effects with secondary shades. Renders slower than 100ms
  // and failed renders use "error".
  return !color || color.startsWith('primary') || color.startsWith('tertiary') || color === 'error';
}

function isEffectColor(color: string | undefined): boolean {
  return !!color && color.startsWith('secondary');
}

/**
 * Returns the top-level prop names of a "Changed Props" diff generated by React development builds.
 */
function readChangedProps(properties: Array<[string, string]>): { changed: string[]; deeplyEqual: string[] } {
  const changed = new Set<string>();
  const deeplyEqual = new Set<string>();
  for (const [label, value] of properties) {
    // Labels are "<marker>\u00a0<indent><key>": "-" removed, "+" added, "\u2007" unchanged reference container.
    // Nested keys are indented with extra non-breaking spaces.
    const marker = label[0];
    if (label[1] !== '\u00a0' || label[2] === '\u00a0') continue;
    const key = label.slice(2);
    if (marker === '-' || marker === '+') {
      changed.add(key);
    } else if (marker === '\u2007') {
      changed.add(key);
      if (typeof value === 'string' && value.includes(DEEPLY_EQUAL_HINT)) {
        deeplyEqual.add(key);
      }
    }
  }
  return { changed: [...changed], deeplyEqual: [...deeplyEqual] };
}

export function loadTrace(path: string): TraceEvent[] {
  let buffer = readFileSync(path);
  if (buffer[0] === 0x1f && buffer[1] === 0x8b) {
    buffer = gunzipSync(buffer);
  }
  const parsed = JSON.parse(buffer.toString('utf8')) as TraceEvent[] | { traceEvents: TraceEvent[] };
  return Array.isArray(parsed) ? parsed : parsed.traceEvents;
}

function collectTrackEntries(events: TraceEvent[]): TrackEntry[] {
  const entries: TrackEntry[] = [];
  const openMeasures = new Map<string, { event: TraceEvent; detail: DevToolsDetail }>();

  for (const event of events) {
    if (event.name === 'TimeStamp') {
      const data = event.args?.data ?? {};
      const track = data['track'];
      const start = data['start'];
      const end = data['end'];
      if (typeof track !== 'string' || typeof start !== 'number' || typeof end !== 'number') continue;
      const trackGroup = typeof data['trackGroup'] === 'string' ? data['trackGroup'] : undefined;
      if (track !== COMPONENTS_TRACK && trackGroup !== SCHEDULER_TRACK_GROUP) continue;
      const name = String(data['message'] ?? data['name'] ?? '');
      // React logs zero width "<Track> Track" entries to make the tracks appear in a fixed order.
      if (name.endsWith(' Track') && start === end) continue;
      entries.push({ name, start, end, track, trackGroup, color: data['color'] as string | undefined });
      continue;
    }

    // performance.measure() calls with a devtools detail: changed props, mounts and update triggers.
    if (event.cat !== 'blink.user_timing') continue;
    const id = `${event.name}|${event.id2?.local ?? event.id2?.global ?? event.id ?? ''}`;
    if (event.ph === 'b' || event.ph === 'n') {
      const detail = parseDetail(event);
      if (!detail?.track) continue;
      if (detail.track !== COMPONENTS_TRACK && detail.trackGroup !== SCHEDULER_TRACK_GROUP) continue;
      if (event.ph === 'n') {
        entries.push(toEntry(event, detail, event.ts));
      } else {
        openMeasures.set(id, { event, detail });
      }
    } else if (event.ph === 'e') {
      const open = openMeasures.get(id);
      if (open) {
        openMeasures.delete(id);
        entries.push(toEntry(open.event, open.detail, event.ts));
      }
    }
  }
  return entries;
}

function toEntry(event: TraceEvent, detail: DevToolsDetail, end: number): TrackEntry {
  return {
    name: event.name.startsWith(CHANGED_PROPS_PREFIX) ? event.name.slice(1) : event.name,
    start: event.ts,
    end,
    track: detail.track!,
    trackGroup: detail.trackGroup,
    color: detail.color,
    properties: detail.properties,
  };
}

function findMarkTs(events: TraceEvent[], name: string, which: 'first' | 'last'): number | undefined {
  const matches = events.filter((event) => event.cat === 'blink.user_timing' && event.name === name);
  const match = which === 'first' ? matches[0] : matches[matches.length - 1];
  return match?.ts;
}

function findWindowStart(events: TraceEvent[]): number {
  const action = findMarkTs(events, ACTION_MARK, 'last');
  if (action !== undefined) return action;
  const navigations = events.filter(
    (event) =>
      event.name === 'navigationStart' &&
      String(event.args?.data?.['documentLoaderURL'] ?? '').startsWith('http') &&
      event.args?.data?.['isOutermostMainFrame'] !== false,
  );
  if (navigations.length) return navigations[navigations.length - 1]!.ts;
  // Loops instead of Math.min(...array): traces contain more events than the maximum number of arguments.
  let start = Infinity;
  for (const event of events) {
    if (event.ts > 0 && event.ts < start) start = event.ts;
  }
  return start;
}

function findTraceEnd(events: TraceEvent[]): number {
  let end = -Infinity;
  for (const event of events) {
    end = Math.max(end, event.ts + (event.dur ?? 0));
  }
  return end;
}

function findRendererMainThread(events: TraceEvent[]): { pid: number; tid: number } | undefined {
  const counts = new Map<string, number>();
  for (const event of events) {
    if (event.name === 'TimeStamp' || event.name === 'navigationStart') {
      const key = `${event.pid}:${event.tid}`;
      counts.set(key, (counts.get(key) ?? 0) + 1);
    }
  }
  const best = [...counts.entries()].toSorted((a, b) => b[1] - a[1])[0];
  if (!best) return undefined;
  const [pid, tid] = best[0].split(':').map(Number);
  return { pid: pid!, tid: tid! };
}

const SCRIPTING_EVENTS = new Set([
  'EvaluateScript',
  'v8.evaluateModule',
  'FunctionCall',
  'TimerFire',
  'FireAnimationFrame',
  'FireIdleCallback',
  'EventDispatch',
  'RunMicrotasks',
  'v8.compile',
  'v8.compileModule',
]);

function computeMainThread(events: TraceEvent[], start: number, end: number): TraceSummary['mainThread'] {
  const thread = findRendererMainThread(events);
  const stats: TraceSummary['mainThread'] = {
    taskMs: 0,
    longTasks: 0,
    longestTaskMs: 0,
    totalBlockingTimeMs: 0,
    scriptingMs: 0,
    styleMs: 0,
    layoutMs: 0,
    paints: 0,
  };
  if (!thread) return stats;

  const threadEvents = events
    .filter(
      (event) =>
        event.ph === 'X' &&
        event.pid === thread.pid &&
        event.tid === thread.tid &&
        event.ts >= start &&
        event.ts <= end,
    )
    .toSorted((a, b) => a.ts - b.ts || (b.dur ?? 0) - (a.dur ?? 0));

  // Only count the outermost scripting event, nested FunctionCall/RunMicrotasks would be counted twice otherwise.
  let scriptingEnd = -Infinity;
  for (const event of threadEvents) {
    const durationMs = (event.dur ?? 0) / 1000;
    if (event.name === 'RunTask') {
      stats.taskMs += durationMs;
      stats.longestTaskMs = Math.max(stats.longestTaskMs, durationMs);
      if (durationMs > LONG_TASK_MS) {
        stats.longTasks++;
        stats.totalBlockingTimeMs += durationMs - LONG_TASK_MS;
      }
    } else if (SCRIPTING_EVENTS.has(event.name)) {
      if (event.ts >= scriptingEnd) {
        stats.scriptingMs += durationMs;
        scriptingEnd = event.ts + (event.dur ?? 0);
      }
    } else if (event.name === 'UpdateLayoutTree') {
      stats.styleMs += durationMs;
    } else if (event.name === 'Layout') {
      stats.layoutMs += durationMs;
    } else if (event.name === 'Paint') {
      stats.paints++;
    }
  }

  return {
    taskMs: round(stats.taskMs),
    longTasks: stats.longTasks,
    longestTaskMs: round(stats.longestTaskMs),
    totalBlockingTimeMs: round(stats.totalBlockingTimeMs),
    scriptingMs: round(stats.scriptingMs),
    styleMs: round(stats.styleMs),
    layoutMs: round(stats.layoutMs),
    paints: stats.paints,
  };
}

function readSource(properties: Array<[string, string]> | null | undefined): string | undefined {
  if (!properties) return undefined;
  const component = properties.find(([key]) => key === 'Component name')?.[1];
  const method = properties.find(([key]) => key === 'Method name')?.[1];
  if (!component && !method) return undefined;
  return [component, method].filter(Boolean).join(' ');
}

export function analyzeTrace(events: TraceEvent[]): TraceSummary {
  const start = findWindowStart(events);
  const end = findMarkTs(events, IDLE_MARK, 'last') ?? findTraceEnd(events);
  const entries = collectTrackEntries(events).filter((entry) => entry.start >= start && entry.start <= end);

  const react: TraceSummary['react'] = {
    renderPasses: 0,
    renderMs: 0,
    commits: 0,
    commitMs: 0,
    effectsMs: 0,
    componentRenders: 0,
    mounts: 0,
    unmounts: 0,
    cascadingUpdates: 0,
    byTrack: {},
    updateSources: {},
    cascadingUpdateSources: {},
  };
  const components = new Map<string, ComponentStats>();
  let lastCommitEnd = start;

  for (const entry of entries) {
    const durationMs = (entry.end - entry.start) / 1000;

    if (entry.trackGroup === SCHEDULER_TRACK_GROUP) {
      const track = (react.byTrack[entry.track] ??= { renders: 0, renderMs: 0, commits: 0, commitMs: 0, effectsMs: 0 });
      if (entry.name === 'Render') {
        react.renderPasses++;
        react.renderMs += durationMs;
        track.renders++;
        track.renderMs += durationMs;
      } else if (entry.name === 'Commit') {
        react.commits++;
        react.commitMs += durationMs;
        track.commits++;
        track.commitMs += durationMs;
        lastCommitEnd = Math.max(lastCommitEnd, entry.end);
      } else if (entry.name === 'Remaining Effects') {
        react.effectsMs += durationMs;
        track.effectsMs += durationMs;
      } else if (entry.name === 'Cascading Update') {
        react.cascadingUpdates++;
        const source = readSource(entry.properties);
        if (source) increment(react.cascadingUpdateSources, source);
      } else if (entry.name === 'Update') {
        const source = readSource(entry.properties);
        if (source) increment(react.updateSources, source);
      }
      continue;
    }

    if (entry.name === 'Mount' || entry.name === 'Reconnect') {
      react.mounts++;
      continue;
    }
    if (entry.name === 'Unmount' || entry.name === 'Disconnect') {
      react.unmounts++;
      continue;
    }

    const stats =
      components.get(entry.name) ??
      ({
        name: entry.name,
        renders: 0,
        renderMs: 0,
        maxRenderMs: 0,
        effects: 0,
        effectMs: 0,
        changedPropsRenders: 0,
        changedProps: {},
        deeplyEqualProps: {},
      } satisfies ComponentStats);
    components.set(entry.name, stats);

    if (isEffectColor(entry.color)) {
      stats.effects++;
      stats.effectMs += durationMs;
    } else if (isRenderColor(entry.color) || entry.properties) {
      react.componentRenders++;
      stats.renders++;
      stats.renderMs += durationMs;
      stats.maxRenderMs = Math.max(stats.maxRenderMs, durationMs);
      if (entry.properties?.length) {
        const { changed, deeplyEqual } = readChangedProps(entry.properties);
        stats.changedPropsRenders++;
        changed.forEach((key) => increment(stats.changedProps, key));
        deeplyEqual.forEach((key) => increment(stats.deeplyEqualProps, key));
      }
    }
  }

  const queryRequests = events.filter((event) => {
    if (event.name !== 'ResourceSendRequest' || event.ts < start || event.ts > end) return false;
    const url = String(event.args?.data?.['url'] ?? '');
    return /\/api\/v1\/query(_range)?(\?|$)/.test(url);
  }).length;

  return {
    windowMs: round((end - start) / 1000),
    lastCommitMs: round((lastCommitEnd - start) / 1000),
    react: {
      ...react,
      renderMs: round(react.renderMs),
      commitMs: round(react.commitMs),
      effectsMs: round(react.effectsMs),
      byTrack: Object.fromEntries(
        Object.entries(react.byTrack).map(([track, stats]) => [
          track,
          {
            ...stats,
            renderMs: round(stats.renderMs),
            commitMs: round(stats.commitMs),
            effectsMs: round(stats.effectsMs),
          },
        ]),
      ),
    },
    mainThread: computeMainThread(events, start, end),
    network: { queryRequests },
    components: [...components.values()]
      .map((stats) =>
        Object.assign(stats, {
          renderMs: round(stats.renderMs),
          maxRenderMs: round(stats.maxRenderMs),
          effectMs: round(stats.effectMs),
        }),
      )
      .toSorted((a, b) => b.renderMs - a.renderMs || b.renders - a.renders),
  };
}

function formatTopRecord(record: Record<string, number>, limit: number): string {
  return Object.entries(record)
    .toSorted((a, b) => b[1] - a[1])
    .slice(0, limit)
    .map(([key, count]) => `${key} (${count})`)
    .join(', ');
}

/**
 * Formats a summary as Markdown, listing the components with the highest render time.
 */
export function formatSummary(summary: TraceSummary, top = 25): string {
  const { react, mainThread } = summary;
  const lines = [
    '| Metric | Value |',
    '| --- | --- |',
    `| Window / last React commit | ${summary.windowMs} ms / ${summary.lastCommitMs} ms |`,
    `| React render passes / render time | ${react.renderPasses} / ${react.renderMs} ms |`,
    `| React commits / commit time / passive effects | ${react.commits} / ${react.commitMs} ms / ${react.effectsMs} ms |`,
    `| Component renders / mounts / unmounts | ${react.componentRenders} / ${react.mounts} / ${react.unmounts} |`,
    `| Cascading updates | ${react.cascadingUpdates} |`,
    `| Main thread tasks / long tasks / longest | ${mainThread.taskMs} ms / ${mainThread.longTasks} / ${mainThread.longestTaskMs} ms |`,
    `| Total blocking time | ${mainThread.totalBlockingTimeMs} ms |`,
    `| Scripting / style / layout / paints | ${mainThread.scriptingMs} ms / ${mainThread.styleMs} ms / ${mainThread.layoutMs} ms / ${mainThread.paints} |`,
    `| Query requests | ${summary.network.queryRequests} |`,
    '',
  ];

  const tracks = Object.entries(react.byTrack).filter(([, stats]) => stats.renders || stats.commits);
  if (tracks.length) {
    lines.push(
      '| Scheduler track | Renders | Render ms | Commits | Commit ms | Effects ms |',
      '| --- | --- | --- | --- | --- | --- |',
    );
    for (const [track, stats] of tracks) {
      lines.push(
        `| ${track} | ${stats.renders} | ${stats.renderMs} | ${stats.commits} | ${stats.commitMs} | ${stats.effectsMs} |`,
      );
    }
    lines.push('');
  }

  if (Object.keys(react.cascadingUpdateSources).length) {
    lines.push(`Cascading updates scheduled by: ${formatTopRecord(react.cascadingUpdateSources, 10)}`, '');
  }
  if (Object.keys(react.updateSources).length) {
    lines.push(`Updates scheduled by: ${formatTopRecord(react.updateSources, 10)}`, '');
  }

  lines.push(
    '| Component | Renders | Render ms (inclusive) | Max ms | Effects ms | Changed props (dev) | Deeply equal props (dev) |',
    '| --- | --- | --- | --- | --- | --- | --- |',
  );
  for (const component of summary.components.slice(0, top)) {
    lines.push(
      `| ${component.name} | ${component.renders} | ${component.renderMs} | ${component.maxRenderMs} | ${component.effectMs} | ${formatTopRecord(component.changedProps, 4)} | ${formatTopRecord(component.deeplyEqualProps, 4)} |`,
    );
  }
  return lines.join('\n');
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const args = process.argv.slice(2);
  const path = args.find((arg) => !arg.startsWith('--'));
  if (!path) {
    console.error('Usage: node trace-analyzer.ts <trace.json|trace.json.gz> [--top=30] [--json]');
    process.exit(1);
  }
  const top = Number(args.find((arg) => arg.startsWith('--top='))?.split('=')[1] ?? 30);
  const summary = analyzeTrace(loadTrace(path));
  console.log(args.includes('--json') ? JSON.stringify(summary, null, 2) : formatSummary(summary, top));
}
